import fs from 'node:fs'
import path from 'node:path'
import assert from 'node:assert/strict'
import { pathToFileURL } from 'node:url'
import { chromium } from 'playwright'

const browser = await chromium.launch()
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
await context.route(/^https?:\/\//, route => route.request().url().startsWith('http://127.0.0.1:24318/') ? route.continue() : route.abort())
const report = { guide: [], gallery: {}, ppt: {} }
try {
  const page = await context.newPage()
  const failures = []
  page.on('pageerror', error => failures.push(error.message))
  for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: 1000 })
    await page.goto('http://127.0.0.1:24318/mcu/book-guide/index.html')
    await page.evaluate(() => document.fonts.ready)
    const measured = await page.evaluate(() => ({
      width: innerWidth, scroll: document.documentElement.scrollWidth,
      images: Array.from(document.images).map(im => ({ src: im.getAttribute('src'), loaded: im.complete && im.naturalWidth > 0 })),
      editable: document.querySelectorAll('[contenteditable="true"]').length,
      text: document.querySelector('main').textContent,
      main: document.querySelector('main').getBoundingClientRect().toJSON(),
    }))
    assert.ok(measured.scroll <= width + 1, `guide width ${width}: horizontal overflow ${measured.scroll}`)
    assert.ok(measured.images.every(im => im.loaded), 'guide image missing')
    assert.equal(measured.editable, 0)
    assert.ok(measured.text.includes('141 张机制动画'))
    assert.ok(measured.text.includes('七份附录的维护说明'))
    await page.locator('#toc-toggle').click()
    await page.locator('.toc-item').filter({ hasText: '参与校对与贡献' }).click()
    await page.waitForFunction(() => location.hash === '#s-04')
    if (width === 390) assert.equal(await page.locator('#toc').evaluate(el => el.classList.contains('toc-open')), false)
    await page.goto('http://127.0.0.1:24318/mcu/book-guide/index.html')
    await page.screenshot({ path: `.temp/skill-closeout/guide-${width}.png`, fullPage: true })
    report.guide.push({ width, scrollWidth: measured.scroll, imageLoaded: true, toc: true, editable: measured.editable })
  }
  await page.goto('http://127.0.0.1:24318/mcu/reference/book.html')
  const link = page.getByRole('link', { name: '打开精排导读', exact: true })
  await link.click()
  await page.waitForURL('**/mcu/book-guide/index.html')
  assert.equal(failures.length, 0, failures.join('\n'))
  report.guideEntry = 'PASS'

  await page.goto(pathToFileURL(path.resolve('video/assets/social-cards/book/index.html')).href)
  await page.locator('img').evaluateAll(els => els.forEach(el => el.loading = 'eager'))
  await page.waitForFunction(() => Array.from(document.images).every(im => im.complete && im.naturalWidth > 0))
  report.gallery.images = await page.locator('img').count()
  assert.equal(report.gallery.images, 30)
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))

  await page.setViewportSize({ width: 1600, height: 900 })
  await page.goto(pathToFileURL(path.resolve('.trellis/tasks/11-02-skill-remaster/deliverables/ppt/index.html')).href)
  await page.locator('.slide').first().waitFor()
  assert.equal(await page.locator('.slide').count(), 13)
  await page.locator('#ppt-low-power-btn').click()
  await page.waitForTimeout(800)
  await page.keyboard.press('ArrowRight')
  assert.equal(await page.evaluate(() => window.__currentSlideIndex), 1)
  await page.waitForTimeout(750)
  await page.keyboard.press('ArrowLeft')
  assert.equal(await page.evaluate(() => window.__currentSlideIndex), 0)
  const popupPromise = page.waitForEvent('popup')
  await page.locator('#ppt-presenter-btn').click()
  let audience = await popupPromise
  await audience.waitForLoadState('domcontentloaded')
  await page.waitForFunction(() => document.querySelector('#ppt-sync')?.dataset.state === 'synced')
  await page.locator('#ppt-next').click()
  await audience.waitForFunction(() => window.__currentSlideIndex === 1)
  await page.locator('#ppt-grid').click()
  assert.equal(await page.locator('.ppt-overview-page').count(), 13)
  await page.locator('.ppt-overview-page').nth(5).click()
  await audience.waitForFunction(() => window.__currentSlideIndex === 5)
  const notes = page.locator('#ppt-note-editor')
  const old = await notes.inputValue()
  await notes.fill(old + '\n本地验证备注')
  await page.waitForTimeout(500)
  await notes.dispatchEvent('blur')
  await page.locator('#ppt-next').click()
  await page.locator('#ppt-prev').click()
  assert.ok((await notes.inputValue()).includes('本地验证备注'))
  await notes.fill(old)
  await page.bringToFront()
  await page.locator('#ppt-timer-toggle').click()
  await page.waitForFunction(() => document.querySelector('#ppt-clock').textContent !== '00:00', { }, { timeout: 10000 })
  assert.notEqual(await page.locator('#ppt-clock').textContent(), '00:00')
  await page.locator('#ppt-timer-toggle').click()
  await page.locator('#ppt-timer-reset').click()
  await page.locator('#ppt-settings').click()
  await page.locator('[data-screen-choice="black"]').click()
  await audience.waitForFunction(() => getComputedStyle(document.querySelector('#ppt-audience-cover')).display !== 'none')
  await page.locator('[data-screen-choice="white"]').click()
  await page.locator('[data-screen-choice="frozen"]').click()
  await page.locator('#ppt-dialog-close').click()
  await page.locator('#ppt-rehearsal').click()
  assert.equal(await page.evaluate(() => window.__pptPresenter.debugState().rehearsalActive), true)
  await page.locator('#ppt-rehearsal').click()
  assert.equal(await page.locator('#ppt-dialog-title').textContent(), '排练记录')
  await page.locator('#ppt-dialog-close').click()
  await page.locator('[data-ppt-tool="circle"]').click()
  const ink = await page.locator('#ppt-presenter-ink').boundingBox()
  await page.mouse.move(ink.x + ink.width * .3, ink.y + ink.height * .3)
  await page.mouse.down()
  await page.mouse.move(ink.x + ink.width * .6, ink.y + ink.height * .6, { steps: 10 })
  await page.mouse.up()
  assert.equal(await page.evaluate(() => window.__pptPresenter.debugState().circles.length), 1)
  await page.locator('#ppt-ink-clear').click()
  assert.equal(await page.evaluate(() => window.__pptPresenter.debugState().circles.length), 0)
  await page.locator('[data-ppt-tool="laser"]').click()
  assert.equal(await page.evaluate(() => window.__pptPresenter.debugState().annotationTool), 'laser')
  await page.locator('[data-ppt-tool="laser"]').click()
  await page.locator('#ppt-settings').click()
  await page.locator('#ppt-auto-seconds-setting').fill('1')
  await page.locator('label[for="ppt-auto-enabled-setting"]').click()
  assert.equal(await page.locator('#ppt-auto-enabled-setting').isChecked(), true)
  await page.locator('#ppt-settings-save').click()
  await page.bringToFront()
  // The audience was deliberately frozen above: auto advance must pause.
  await page.waitForTimeout(1400)
  assert.equal(await page.evaluate(() => window.__currentSlideIndex), 5)
  await page.locator('#ppt-settings').click()
  await page.locator('[data-screen-choice="normal"]').click()
  await page.locator('#ppt-dialog-close').click()
  await page.waitForFunction(() => window.__currentSlideIndex === 6, {}, { timeout: 15000 })
  await page.locator('#ppt-auto-toggle').click()
  assert.equal(await page.evaluate(() => window.__pptPresenter.debugState().autoEnabled), false)
  await audience.waitForFunction(() => window.__currentSlideIndex === 6)
  await page.locator('#ppt-last').click()
  await audience.waitForFunction(() => window.__currentSlideIndex === 12)
  await page.locator('#ppt-first').click()
  await audience.waitForFunction(() => window.__currentSlideIndex === 0)
  await page.locator('#ppt-preflight').click()
  assert.equal(await page.locator('#ppt-dialog-title').textContent(), '演前检查')
  await page.locator('#ppt-dialog-close').click()
  await audience.close()
  await page.waitForFunction(() => document.querySelector('#ppt-sync')?.dataset.state === 'disconnected')
  const reopened = page.waitForEvent('popup')
  await page.locator('#ppt-reopen').click()
  audience = await reopened
  await page.waitForFunction(() => document.querySelector('#ppt-sync')?.dataset.state === 'synced')
  await page.screenshot({ path: '.temp/skill-closeout/ppt-presenter.png' })
  report.ppt = { slides: 13, synced: true, navigation: true, grid: true, notes: true, timer: true, screenModes: true, preflight: true, reopen: true, rehearsal: true, annotations: true, autoAdvance: true }
  fs.writeFileSync('.temp/skill-closeout/browser-report.json', JSON.stringify(report, null, 2))
  console.log(JSON.stringify(report, null, 2))
} finally {
  await browser.close()
}
