"""Contract for the handraw knowledge track (assets/illustrations/handraw/).

The family is generated by tools/handraw_track (hd.py + fig_chNN.py, seeded,
deterministic) and shipped as PNG (+ committed SVG source where present).
It is excluded from test_sample_svg_c's hash contract on purpose: these are
knowledge-track concept figures, not the paper-card figure system.

Gates enforced here:
- every SVG parses as XML and carries the honesty badge 原理示意 / 非实拍;
- no script/foreignObject/external references inside the SVGs;
- every handraw file referenced by docs exists, and zh/en reference the same
  set (bilingual symmetry);
- every PNG has a matching SVG source (or is an AI-generated plate from the
  ch00–ch12 batch, which is fine: those were committed without sources).
"""
from __future__ import annotations

import re
import unittest
import xml.etree.ElementTree as ET
from pathlib import Path

BOOK = Path(__file__).resolve().parents[1]
REPO = BOOK.parent
DIR = REPO / "assets" / "illustrations" / "handraw"
BADGE = "原理示意 / 非实拍"


class HandrawTrackTests(unittest.TestCase):
    def test_svgs_parse_and_carry_honesty_badge(self) -> None:
        svgs = sorted(DIR.glob("*.svg"))
        self.assertGreater(len(svgs), 0)
        for path in svgs:
            text = path.read_text(encoding="utf-8")
            ET.fromstring(text)
            self.assertIn(BADGE, text, path.name)
            for banned in ("<script", "<foreignObject", "xlink:href", "url("):
                self.assertNotIn(banned, text, (path.name, banned))

    def test_docs_reference_existing_files_and_stay_symmetric(self) -> None:
        zh_refs: set[str] = set()
        en_refs: set[str] = set()
        for doc in sorted((REPO / "docs").glob("*.md")):
            zh_refs |= set(re.findall(r"illustrations/handraw/([^)\"]+)",
                                      doc.read_text(encoding="utf-8")))
        for doc in sorted((REPO / "docs" / "en").glob("*.md")):
            en_refs |= set(re.findall(r"illustrations/handraw/([^)\"]+)",
                                      doc.read_text(encoding="utf-8")))
        for name in sorted(zh_refs):
            self.assertTrue((DIR / name).is_file(), name)
        for name in sorted(en_refs):
            self.assertTrue((DIR / name).is_file(), name)
        # chapters embed the same figure set in both languages
        self.assertEqual(zh_refs, en_refs)


if __name__ == "__main__":
    unittest.main()
